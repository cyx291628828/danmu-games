/**
 * ============================================================================
 * games/semantic/pos.js — 答案词性启发式判定（名词/动词/形容词）
 * ============================================================================
 * 词向量模型不带词性信息，这里用字面规则做「提示用」的近似判定：
 *   1. 名词后缀（员/家/师/子/头/性/度/感…）命中 → 名词
 *   2. 「化」结尾（除少数例外）→ 动词
 *   3. 首字/尾字命中形容词字素（大小多少高矮美丑…）→ 形容词
 *   4. 首字/尾字命中动词字素（吃打拿看听说…）→ 动词
 *   5. 其余默认 → 名词（词库高频词中名词占绝对多数）
 * 判定是启发式的，个别词会标错（如「文化」会判成动词）——仅用于直播提示参考。
 * ============================================================================
 */
'use strict';

const NOUN_SUFFIX = new Set(
  ('员家师者子头娃哥姐弟妹爷奶' +
    '性度感率值量数力气光色味线点面片张块支棵颗朵间层批次号' +
    '店馆院场局所部处室厅村镇城州省县国界区站' +
    '山江河湖海岛滩林树花草苗稻麦豆菜瓜果' +
    '鸟鱼虫猫狗马牛羊猪鸡鸭鹅虎狼猴象' +
    '车船机弹枪炮剑刀弓琴棋书画球拍' +
    '病炎癌症伤疤痕迹纹章旗鼓钟铃灯表尺秤叉币卡票券').split('')
);

const VERB_CHARS = new Set(
  ('吃喝打拿想做用买开关进出回来去到给带拉推抱背飞跳睡醒笑哭唱读写画算' +
    '走跑站坐看听说学教炒煮蒸烤熬洗刷扔捡扫拖搬砸修拆锁送递接抢偷骗骂' +
    '咬踢举扛挑抬追赶逃攻击防守卫包装订').split('')
);

const ADJ_CHARS = new Set(
  ('大小多少高低长短快慢美丑好坏新旧热冷暖湿干硬软松紧苦甜酸辣咸香臭' +
    '亮暗明昏真假贵贱富穷忙闲肥瘦胖扁圆方尖粗细浓淡深浅重轻').split('')
);

/** 名词后缀优先；「化」结尾判动词；形容词/动词字素其次；默认名词。
 *  3 字以上只看尾字（首字误判率高，如「高等教育」的高）。 */
function pos(word) {
  const w = String(word || '').trim();
  if (!w) return '名词';
  const last = w[w.length - 1];
  const first = w[0];
  if (NOUN_SUFFIX.has(last)) return '名词';
  if (w.endsWith('化') && w.length >= 2) return '动词';
  const adjHit = ADJ_CHARS.has(last) || (w.length === 2 && ADJ_CHARS.has(first));
  if (adjHit) return '形容词';
  const verbHit = VERB_CHARS.has(last) || (w.length === 2 && VERB_CHARS.has(first));
  if (verbHit) return '动词';
  return '名词';
}

module.exports = { pos };
